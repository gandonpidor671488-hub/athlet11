    static string Norm(string s) => s.ToLowerInvariant().Replace('ё', 'е');

    static readonly char[] Seps = { ' ', '-', '(', ')', '—' };

    /// <summary>Подсказки по тому, что человек уже ввёл (до первой запятой). Пусто — подсказки не нужны.</summary>
    public static List<string> Suggest(string? text)
    {
        var raw = text ?? "";
        int comma = raw.IndexOf(',');
        var q = Norm(comma >= 0 ? raw.Substring(0, comma) : raw).Trim();
        if (comma >= 0 && All.Any(r => Norm(r) == q)) return new();   // регион уже выбран, дальше человек пишет сам
        if (q.Length == 0) return All.ToList();                        // поле пустое — весь список
        var res = new List<(int score, int idx, string r)>();
        for (int i = 0; i < All.Count; i++)
        {
            var n = Norm(All[i]);
            int score = n.StartsWith(q) ? 0
                      : n.Split(Seps, StringSplitOptions.RemoveEmptyEntries).Any(w => w.StartsWith(q)) ? 1
                      : n.Contains(q) ? 2 : -1;
            if (score >= 0) res.Add((score, i, All[i]));
        }
        return res.OrderBy(x => x.score).ThenBy(x => x.idx).Select(x => x.r).ToList();
    }

    /// <summary>null — адрес нормальный, иначе текст ошибки.</summary>
    public static string? CheckAddress(string? text)
    {
        var t = (text ?? "").Trim(' ', ',');
        if (t.Length == 0) return "Введите адрес доставки";
        var n = Norm(t);
        if (All.Any(r => Norm(r) == n)) return "Дополните адрес: город, улица, дом";
        return null;
    }
